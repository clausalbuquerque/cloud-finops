_DEFAULT_SOURCE_IDS = {source.source_id for source in DEFAULT_GCP_SOURCES}


class SourceRegistry:
    def __init__(self, sources: tuple[ProviderDocSource, ...] = DEFAULT_GCP_SOURCES) -> None:
        self._sources = {source.source_id: source for source in sources}

        duplicate_count = len(sources) - len(self._sources)
        if duplicate_count:
            raise ValueError(f"Source registry contains {duplicate_count} duplicate source_id values")

        for source in sources:
            self._validate_source(source)

    def list_sources(self) -> list[ProviderDocSource]:
        return list(self._sources.values())

    def get_source(self, source_id: str) -> ProviderDocSource:
        try:
            return self._sources[source_id]
        except KeyError as exc:
            raise KeyError(f"Unknown source_id: {source_id}") from exc

    @staticmethod
    def _validate_source(source: ProviderDocSource) -> None:
        host = urlparse(source.source_url).hostname or ""
        if host not in _ALLOWED_HOSTS:
            raise ValueError(f"Untrusted source host for {source.source_id}: {host}")

        # New sources must include explicit manual-review metadata before onboarding.
        if source.source_id not in _DEFAULT_SOURCE_IDS:
            if not source.review_ticket or not source.approved_by:
                raise ValueError(
                    f"Source {source.source_id} is missing manual review approval metadata "
                    "(review_ticket and approved_by are required)"
                )
